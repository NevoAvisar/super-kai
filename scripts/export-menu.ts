/**
 * Generates, from the catalog data (so docs never drift from the site):
 *   docs/signature-menu.md  — 15 signature dishes: menu breakdown + prompts
 *   docs/image-prompts.md   — aiImagePrompt for every dish in the catalog
 *   docs/image-prompts.json — same, machine-readable for batch generation
 *   npm run menu:export
 */
import fs from "node:fs";
import path from "node:path";
import sample from "../src/data/gourmet-sample.json";
import { seedCategories, seedProducts, withSlugs, type SeedProduct } from "../src/data/catalog-seed";
import { DIETARY, type DietaryTag } from "../src/lib/dietary";
import { pricePer100g } from "../src/lib/pricing";

type P = SeedProduct & { slug: string };
const products = sample.products as P[];
const ils = (agorot: number) => `₪${(agorot / 100).toFixed(2)}`;

function priceCells(p: P) {
  const agorot = Math.round(p.price * 100);
  const unit = p.saleUnit ?? "KG";
  const per100 = pricePer100g(agorot, unit, p.unitWeightGrams);
  const sold = unit === "KG" ? `${ils(agorot)} / kg` : `${ils(agorot)} / ${p.unitLabel ?? "unit"}`;
  return { sold, per100: per100 === null ? "—" : ils(per100) };
}

const badges = (p: P) => (p.dietary ?? []).map((t) => DIETARY[t as DietaryTag].label).join(" · ") || "—";

let md = `# Super-Kai · Signature Menu & AI Photo Prompts

> Generated from \`src/data/gourmet-sample.json\` by \`npm run menu:export\`. Edit the JSON, not this file.

**15 signature dishes** across ${new Set(products.map((p) => p.categorySlug)).size} categories. KG dishes are sold in 0.25 kg steps; soups, quiches, strudels and jars are sold per unit. Meat dishes contain no dairy.

## How to use the photo prompts

1. Paste a dish's prompt into your image generator.
   - **Midjourney:** append this suffix:
     \`\`\`text
     ${sample.imageStyle.midjourneySuffix}
     \`\`\`
   - **DALL·E / ChatGPT:** ${sample.imageStyle.dalleNote}
2. Save the result as \`public/products/<slug>.jpg\` (or \`.webp\` / \`.png\`). The site picks it up automatically, no code change.
3. Every prompt shares one visual language: warm natural window light, artisanal ceramics / wood / glass jars, shallow depth of field, DSLR look, and **no text, labels, watermarks or hands**.

## Overview

| # | Dish | English | Category | Sold as | Per 100 g | Serving guideline |
|---|------|---------|----------|---------|-----------|-------------------|
`;

products.forEach((p, i) => {
  const cat = seedCategories.find((c) => c.slug === p.categorySlug)!;
  const { sold, per100 } = priceCells(p);
  md += `| ${i + 1} | ${p.name} | ${p.nameEn} | ${cat.name} | ${sold} | ${per100} | ${p.servingGuideEn} |\n`;
});

let n = 0;
for (const cat of seedCategories) {
  const items = products.filter((p) => p.categorySlug === cat.slug);
  if (!items.length) continue;
  md += `\n---\n\n## ${cat.name}\n`;
  for (const p of items) {
    n++;
    const { sold, per100 } = priceCells(p);
    md += `
### ${n}. ${p.nameEn}
**${p.name}** · \`${p.slug}\`${p.promoPercent ? ` · 🏷️ ${p.promoPercent}% off` : ""}

${p.descriptionEn}

${p.description}

| | |
|---|---|
| **Price** | ${sold} |
| **Per 100 g** | ${per100} |
| **Serving** | ${p.servingGuideEn} |
| **הנחיית הגשה** | ${p.servingGuide} |
| **Ingredients** | ${(p.ingredients ?? []).join(", ")} |
| **Badges** | ${badges(p)} |

**Image prompt** → save as \`public/products/${p.slug}.jpg\`
\`\`\`text
${p.aiImagePrompt}
\`\`\`
`;
  }
}

const docs = path.join(process.cwd(), "docs");
fs.writeFileSync(path.join(docs, "signature-menu.md"), md);
console.log(`Wrote docs/signature-menu.md (${products.length} dishes)`);

// ---------------------------------------------------------------------------
// Full catalog prompt sheet
// ---------------------------------------------------------------------------
const all = withSlugs(seedProducts);
const missing = all.filter((p) => !p.aiImagePrompt);
if (missing.length) throw new Error(`Missing aiImagePrompt: ${missing.map((p) => p.slug).join(", ")}`);

const rows = all.map((p) => ({
  slug: p.slug,
  file: `public/products/${p.slug}.jpg`,
  name: p.name,
  category: p.categorySlug,
  aiImagePrompt: p.aiImagePrompt!,
}));
fs.writeFileSync(path.join(docs, "image-prompts.json"), JSON.stringify(rows, null, 2) + "\n");

let sheet = `# Super-Kai · AI Image Prompts (all ${rows.length} dishes)

> Generated by \`npm run menu:export\`. Edit prompts in \`src/data/gourmet-sample.json\` (signatures) or \`src/data/catalog-seed.ts\` (the rest).

Save each image as the file shown and it appears on the site automatically.
**Midjourney suffix:** \`${sample.imageStyle.midjourneySuffix}\` · **DALL·E:** ${sample.imageStyle.dalleNote}
`;
for (const cat of seedCategories) {
  const items = rows.filter((r) => r.category === cat.slug);
  sheet += `\n## ${cat.name} (${items.length})\n`;
  for (const r of items) {
    sheet += `\n**${r.name}** → \`${r.file}\`\n\`\`\`text\n${r.aiImagePrompt}\n\`\`\`\n`;
  }
}
fs.writeFileSync(path.join(docs, "image-prompts.md"), sheet);
console.log(`Wrote docs/image-prompts.md + .json (${rows.length} dishes)`);
